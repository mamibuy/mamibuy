-- ⚠️ 只給本機 supabase 測試用的「推測版」基礎結構（由 src/App.jsx 讀寫的欄位反推）。
-- 正式資料庫已經有這些表，不需要也不要在正式環境執行這支；
-- 全部用 IF NOT EXISTS，就算誤跑也不會動到既有資料表。

create table if not exists public.users (
  id        bigint generated by default as identity primary key,
  name      text not null,
  email     text,
  role      text not null default 'applicant',
  company   text,
  active    boolean not null default true,
  password  text
);

create table if not exists public.vendors (
  id           bigint generated by default as identity primary key,
  name         text,
  tax_id       text,
  bank         text,
  branch       text,
  account_name text,
  account      text,
  theme        text default 'invoice'
);

create table if not exists public.projects (
  id                bigint generated by default as identity primary key,
  applicant         text,
  company           text,
  title             text,
  client_title      text,
  tax_id            text,
  amount            numeric,
  tax_amount        numeric,
  status            text,
  invoice_date      date,
  expected_pay_date date,
  order_no          text,
  pay_method        text,
  invoice_no        text,
  vendor_id         bigint,
  paid              numeric default 0,
  paid_amount       numeric,
  paid_date         text,
  bank_fee          numeric,
  commission        numeric,
  commission_no     text,
  expense_no        text,
  voucher_no        text,
  items_json        text,
  theme             text default 'invoice'
);

create table if not exists public.reconcile_batches (
  id          text primary key,
  file_name   text,
  bank_type   text,
  saved_at    text,
  saved_date  text,
  parse_error text
);

create table if not exists public.reconcile_rows (
  id                 bigint generated by default as identity primary key,
  batch_id           text,
  row_index          int,
  date_val           text,
  amount             numeric,
  summary            text,
  diff               numeric,
  diff_note          text,
  fee                numeric,
  fee_confirmed      boolean default false,
  other_diff         numeric,
  voucher_no         text,
  expense_no         text,
  match_id           bigint,
  match_title        text,
  match_tax_amount   numeric,
  match_client_title text,
  match_order_no     text
);
